"""AWS S3 stand-in: keeps the PDF copy in a local folder.

In the design the PDF copy is saved to AWS storage (an S3 bucket is proposed)
when processing starts, and ``SOURCE_DOCUMENT.checksum`` shows the copy was not
replaced. Here an object key is a file name inside one folder. The prototype
uses SHA-256 for the checksum; the production algorithm is not decided.
"""

from __future__ import annotations

import hashlib
from pathlib import Path


class DocumentStore:
    def __init__(self, folder: Path) -> None:
        self.folder = Path(folder)
        self.folder.mkdir(parents=True, exist_ok=True)

    def _path(self, object_key: str) -> Path:
        # Object keys are generated by the fixtures, never by a request, but
        # refuse anything that would leave the folder all the same.
        path = (self.folder / object_key).resolve()
        if self.folder.resolve() not in path.parents:
            raise ValueError(f"object key outside the document store: {object_key!r}")
        return path

    def put(self, object_key: str, data: bytes) -> str:
        """Save a PDF and return its checksum."""
        path = self._path(object_key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return checksum(data)

    def get(self, object_key: str) -> bytes | None:
        path = self._path(object_key)
        return path.read_bytes() if path.is_file() else None

    def verified_get(self, object_key: str, expected_checksum: str) -> tuple[bytes | None, str]:
        """Return ``(pdf, problem)``.

        ``problem`` is ``""`` when the PDF exists and matches its checksum,
        otherwise ``"missing"`` or ``"checksum mismatch"`` and ``pdf`` is None.
        """
        data = self.get(object_key)
        if data is None:
            return None, "missing"
        if checksum(data) != expected_checksum:
            return None, "checksum mismatch"
        return data, ""


def checksum(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()
